def lookup(code):
    """returns (label, class, cat, violent, attempt)"""
    if code is None or code=="": return ("No charge recorded","none","NONE",0,0)
    code=code.strip().upper()
    att=0
    if code.startswith("110-"):
        att=1; code=code[4:]
    base=code.rstrip("H").rstrip() if code.endswith("H") else code
    base=base.replace("SM","") if base.endswith("SM") else base
    for k in (code, base):
        if k in C:
            l,cl,cat,v=C[k]
            return (l,cl,cat,v,att)
    # AC / VTL junk codes
    if code.startswith("VTL "): code=code[4:]
    if code in C: 
        l,cl,cat,v=C[code]; return (l,cl,cat,v,att)
    if code.startswith("AC") or code.startswith("VTL"):
        return ("Charge not specified in the data","other","OTH",0,att)
    art=code.split(".")[0][:3]
    if art in ART:
        l,cl,cat,v=ART[art]
        return (l,cl,cat,v,att)
    return ("Charge not specified in the data","other","OTH",0,att)
